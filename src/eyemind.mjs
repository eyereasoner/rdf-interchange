// eyemind documents: RDF quads as rdf/4 terms written as JavaScript
// expressions, one per line, and eyemind's conclusion documents read back.
//
// The reader accepts the document forms of the eyemind specification
// (Section 9) and never executes the text. An eyemind Skolem term,
// skolem(Rule, Variable, Arguments), names something a rule says exists; it
// becomes a blank node of scope `skolem` labelled by its canonical text, so
// the same firing always gives the same node.
import { XSD_STRING, fromEyeProlog, quadToNQuad } from './rdf-codec.mjs';
import { atom, compound, numberTerm, variable } from './prolog-term.mjs';

// RDF quads as an eyemind document, for facts_from.
export function compileQuadsToEyemind(quads, { predicate = 'rdf' } = {}) {
  const lines = [
    '// Generated by rdf-interchange.',
    '// RDF terms use rdf(Subject, Predicate, Object, Graph).',
    ...quads.map((q) => quadToEyemind(q, predicate)),
  ];
  return `${lines.join('\n')}\n`;
}

export function quadToEyemind(q, predicate = 'rdf') {
  // quadToNQuad validates the quad as the Prolog writer does.
  quadToNQuad(q);
  return `${predicate}(${toEyemind(q.subject)}, ${toEyemind(q.predicate)}, ${toEyemind(q.object)}, ${toEyemind(q.graph)})`;
}

export function toEyemind(t) {
  if (t.kind === 'namedNode') return `iri(${quote(t.value)})`;
  if (t.kind === 'blankNode') return `bnode(${quote(t.scope)}, ${quote(t.value)})`;
  if (t.kind === 'defaultGraph') return "'default_graph'";
  if (t.kind === 'triple') return `triple(${toEyemind(t.subject)}, ${toEyemind(t.predicate)}, ${toEyemind(t.object)})`;
  if (t.kind === 'literal') {
    let annotation = `datatype(${quote(t.datatype ?? XSD_STRING)})`;
    if (t.language && t.direction) annotation = `lang(${quote(t.language)}, ${quote(t.direction)})`;
    else if (t.language) annotation = `lang(${quote(t.language)})`;
    return `literal(${quote(t.value)}, ${annotation})`;
  }
  throw new Error(`unsupported RDF term kind: ${t?.kind ?? typeof t}`);
}

// The quads of the ground rdf/4 and result_rdf/4 terms of an eyemind
// document, such as the conclusions of a run whose query is result_rdf/4.
export function extractRdfQuadsFromEyemind(source) {
  const quads = [];
  const seen = new Set();
  for (const term of readEyemindDocument(source)) {
    if (term.type !== 'compound' || !['rdf', 'result_rdf'].includes(term.name) || term.args.length !== 4) continue;
    const [subject, predicate, object, graph] = term.args.map((arg) => fromEyeProlog(skolemsAsBlankNodes(arg)));
    const quad = { subject, predicate, object, graph };
    const key = quadToNQuad(quad);
    if (!seen.has(key)) {
      seen.add(key);
      quads.push(quad);
    }
  }
  return quads;
}

function skolemsAsBlankNodes(t) {
  if (t.type === 'compound' && t.name === 'skolem' && t.args.length === 3) {
    return compound('bnode', [atom('skolem'), atom(canonical(t))]);
  }
  if (t.type === 'compound') return compound(t.name, t.args.map(skolemsAsBlankNodes));
  return t;
}

// eyemind's canonical text of a term (its specification, Section 8).
function canonical(t) {
  if (t.type === 'atom') return t.name === '[]' ? '[]' : quote(t.name);
  if (t.type === 'number' || t.type === 'var') return t.name;
  if (t.name === '.' && t.args.length === 2) {
    const items = [];
    let rest = t;
    while (rest.type === 'compound' && rest.name === '.' && rest.args.length === 2) {
      items.push(canonical(rest.args[0]));
      rest = rest.args[1];
    }
    if (!(rest.type === 'atom' && rest.name === '[]')) items.push(`...${canonical(rest)}`);
    return `[${items.join(', ')}]`;
  }
  const args = t.args.map(canonical).join(', ');
  if (/^[A-Za-z_][A-Za-z0-9_]*$/.test(t.name) && !RESERVED.has(t.name) && t.name !== 'struct') return `${t.name}(${args})`;
  return `struct(${quote(t.name)}, ${args})`;
}

const ESCAPES = { '\\': '\\\\', "'": "\\'", '\n': '\\n', '\r': '\\r', '\t': '\\t', '\b': '\\b', '\f': '\\f', '\v': '\\v' };

// An atom as eyemind writes it: single quotes, with control characters and
// line separators escaped.
function quote(text) {
  let out = "'";
  for (const ch of text) {
    const code = ch.codePointAt(0);
    if (ESCAPES[ch] !== undefined) out += ESCAPES[ch];
    else if (code < 0x20 || (code >= 0x7f && code <= 0x9f) || code === 0x2028 || code === 0x2029 ||
             (code >= 0xd800 && code <= 0xdfff)) out += `\\u${code.toString(16).padStart(4, '0')}`;
    else out += ch;
  }
  return `${out}'`;
}

const RESERVED = new Set(('break case catch class const continue debugger default delete do else enum export extends ' +
  'false finally for function if import in instanceof new null return super switch this throw true try typeof var ' +
  'void while with yield let static implements interface package private protected public await arguments eval ' +
  'undefined NaN Infinity').split(' '));

// The terms of an eyemind document, in order. Only string and number
// literals, names, calls of a plain name, arrays, objects and a minus sign on
// a number are accepted; anything else is an error naming its line.
export function readEyemindDocument(source) {
  const tokens = tokenize(String(source));
  let i = 0;
  const peek = () => tokens[i];
  const next = () => tokens[i++];
  const fail = (message, token = peek()) => new Error(`eyemind document, line ${token.line}: ${message}`);
  const expect = (text) => {
    const token = next();
    if (token.text !== text) throw fail(`expected ${text}, found ${token.text || 'the end'}`, token);
  };
  // Items up to the closing bracket, allowing a trailing comma.
  const items = (close, item) => {
    const out = [];
    while (peek().text !== close) {
      out.push(item());
      if (peek().text === ',') next();
      else if (peek().text !== close) throw fail(`expected , or ${close}`);
    }
    next();
    return out;
  };
  const expression = () => {
    const token = next();
    if (token.kind === 'string') return atom(token.value);
    if (token.kind === 'number') return numberTerm(token.value);
    if (token.text === '-' && peek().kind === 'number') return numberTerm(`-${next().value}`);
    if (token.text === '(') {
      const inner = expression();
      expect(')');
      return inner;
    }
    if (token.text === '[') {
      let tail = atom('[]');
      const elements = items(']', () => {
        if (peek().text !== '...') return expression();
        next();
        tail = expression();
        if (peek().text !== ']') throw fail('only the last item of a list may be spread');
        return null;
      }).filter((item) => item !== null);
      return elements.reduceRight((rest, head) => compound('.', [head, rest]), tail);
    }
    if (token.text === '{') {
      const pairs = items('}', () => {
        const key = next();
        if (key.kind !== 'string' && key.kind !== 'name') throw fail('an object key must be a name or a string', key);
        expect(':');
        return compound('=', [atom(key.kind === 'name' ? key.text : key.value), expression()]);
      });
      return pairs.reduceRight((rest, head) => compound('.', [head, rest]), atom('[]'));
    }
    if (token.kind === 'name') {
      if (RESERVED.has(token.text) || token.text.includes('$')) throw fail(`${token.text} is not a term`, token);
      if (peek().text !== '(') return variable(token.text);
      next();
      const args = items(')', expression);
      if (token.text === 'struct') {
        if (!args.length || args[0].type !== 'atom') throw fail('struct needs a name', token);
        return args.length === 1 ? args[0] : compound(args[0].name, args.slice(1));
      }
      return args.length ? compound(token.text, args) : atom(token.text);
    }
    throw fail(`unexpected ${token.text || 'end of document'}`, token);
  };
  const terms = [];
  while (peek().kind !== 'end') {
    if (peek().text === ';') { next(); continue; }
    terms.push(expression());
    const after = peek();
    if (after.text === ';') next();
    else if (after.kind !== 'end' && after.line === tokens[i - 1].line) throw fail(`unexpected ${after.text}`, after);
  }
  return terms;
}

const PUNCTUATION = ['...', '(', ')', '[', ']', '{', '}', ',', ':', ';', '-'];
const NUMBER = /(?:[0-9]+n|(?:[0-9]+\.[0-9]*|\.[0-9]+)(?:[eE][+-]?[0-9]+)?|[0-9]+[eE][+-]?[0-9]+|[0-9]+)/y;
const SIMPLE = { n: '\n', r: '\r', t: '\t', b: '\b', f: '\f', v: '\v', 0: '\0', "'": "'", '"': '"', '\\': '\\' };

function tokenize(text) {
  const tokens = [];
  let line = 1;
  let pos = 0;
  while (pos < text.length) {
    const ch = text[pos];
    if (ch === '\n') { line++; pos++; continue; }
    if (ch === ' ' || ch === '\t' || ch === '\r') { pos++; continue; }
    if (text.startsWith('//', pos)) {
      while (pos < text.length && text[pos] !== '\n') pos++;
      continue;
    }
    if (text.startsWith('/*', pos)) {
      const end = text.indexOf('*/', pos + 2);
      if (end < 0) throw new Error(`eyemind document, line ${line}: unterminated comment`);
      line += text.slice(pos, end).split('\n').length - 1;
      pos = end + 2;
      continue;
    }
    if (ch === "'" || ch === '"') {
      const [value, end] = string(text, pos, line);
      tokens.push({ kind: 'string', value, text: text.slice(pos, end), line });
      pos = end;
      continue;
    }
    if (/[0-9]/.test(ch) || (ch === '.' && /[0-9]/.test(text[pos + 1] ?? ''))) {
      NUMBER.lastIndex = pos;
      const match = NUMBER.exec(text)[0];
      if (/[A-Za-z0-9_$.]/.test(text[pos + match.length] ?? '')) {
        throw new Error(`eyemind document, line ${line}: malformed number ${text.slice(pos, pos + match.length + 1)}`);
      }
      const digits = match.endsWith('n') ? match.slice(0, -1) : match;
      if (/^0[0-9]/.test(digits) && !/[.eE]/.test(digits)) {
        throw new Error(`eyemind document, line ${line}: an integer has no leading zero: ${digits}`);
      }
      tokens.push({ kind: 'number', value: digits, text: match, line });
      pos += match.length;
      continue;
    }
    const name = /[A-Za-z_$][A-Za-z0-9_$]*/y;
    name.lastIndex = pos;
    const match = name.exec(text);
    if (match) {
      tokens.push({ kind: 'name', text: match[0], line });
      pos += match[0].length;
      continue;
    }
    const punctuation = PUNCTUATION.find((p) => text.startsWith(p, pos));
    if (!punctuation) throw new Error(`eyemind document, line ${line}: unexpected ${ch}`);
    tokens.push({ kind: 'punctuation', text: punctuation, line });
    pos += punctuation.length;
  }
  tokens.push({ kind: 'end', text: '', line });
  return tokens;
}

function string(text, start, line) {
  const quoteChar = text[start];
  let out = '';
  let pos = start + 1;
  const fail = (message) => new Error(`eyemind document, line ${line}: ${message}`);
  while (pos < text.length && text[pos] !== quoteChar) {
    const ch = text[pos];
    if (ch === '\n' || ch === '\r') throw fail('unterminated string');
    if ((ch < ' ' && ch !== '\t') || ch === '\x7f') throw fail('a raw control character in a string');
    if (ch !== '\\') { out += ch; pos++; continue; }
    const e = text[pos + 1];
    if (e === undefined) throw fail('unterminated string');
    if (SIMPLE[e] !== undefined && !(e === '0' && /[0-9]/.test(text[pos + 2] ?? ''))) {
      out += SIMPLE[e];
      pos += 2;
    } else if (e === 'x' && /^[0-9a-fA-F]{2}$/.test(text.slice(pos + 2, pos + 4))) {
      out += String.fromCharCode(parseInt(text.slice(pos + 2, pos + 4), 16));
      pos += 4;
    } else if (e === 'u' && text[pos + 2] === '{') {
      const end = text.indexOf('}', pos + 3);
      const hex = text.slice(pos + 3, end);
      if (end < 0 || !/^[0-9a-fA-F]+$/.test(hex) || parseInt(hex, 16) > 0x10ffff) throw fail('malformed \\u{...} escape');
      out += String.fromCodePoint(parseInt(hex, 16));
      pos = end + 1;
    } else if (e === 'u' && /^[0-9a-fA-F]{4}$/.test(text.slice(pos + 2, pos + 6))) {
      out += String.fromCharCode(parseInt(text.slice(pos + 2, pos + 6), 16));
      pos += 6;
    } else if (e === '\n') {
      pos += 2;
    } else if (/[1-9xu]/.test(e)) {
      throw fail(`malformed escape \\${e}`);
    } else {
      out += e;
      pos += 2;
    }
  }
  if (pos >= text.length) throw fail('unterminated string');
  return [out, pos + 1];
}
